"""
app/api/v1/evaluation.py

Person 2 — Validation & Refinement Endpoints

Phase 3 — Technical Evaluation   (compliance scoring)
Phase 4 — Financial Evaluation   (via evaluation_service)
Phase 5 — Combined Scoring & Ranking

POST /api/v1/evaluations/validate
    Validate a generated dossier against tender requirements.
    Automatically triggers a refinement pass if score < 60.

GET  /api/v1/evaluations/
    Placeholder for future list endpoint (Milestone 3).

Blueprint rules enforced here by Python (The Enforcer):
  - Python validates LLM scores fit within the defined rubric max range.
  - Python runs the lowest-price scoring formula (Phase 4 math).
  - Python applies weights (DEFAULT_TECHNICAL_WEIGHT from settings).
  - Python flags close ties (< CLOSE_TIE_THRESHOLD_PCT difference).
  - Python flags abnormally low bids (< ABNORMALLY_LOW_PRICE_THRESHOLD_PCT).
"""

from fastapi import APIRouter, HTTPException, status
from loguru import logger

from app.schemas.evaluation import DossierValidationRequest, ValidationReportResponse
from app.services.evaluation_service import validate_and_refine

router = APIRouter()


@router.post(
    "/validate",
    response_model=ValidationReportResponse,
    summary="Validate & auto-refine a tender response dossier",
    description=(
        "Analyse the conformity of a generated dossier against Moroccan public "
        "procurement requirements (Décret 2-12-349). "
        "If the compliance score is below 60, an automatic refinement pass is "
        "triggered to correct failing sections before re-scoring. "
        "Returns the final score, verdict, eliminating clauses, and actionable recommendations."
    ),
    status_code=status.HTTP_200_OK,
)
async def validate_dossier(payload: DossierValidationRequest) -> ValidationReportResponse:
    """
    Full Person 2 pipeline in a single HTTP call:
      1. LLM validates dossier against requirements
      2. If score < 60 → LLM refines failing sections (up to 2 passes)
      3. Returns best ValidationReportResponse

    Body:
        requirements : dict — extracted from tender PDF by Person 1A
        dossier      : dict — generated by Person 1B's Gemini service
    """
    logger.info(
        "POST /evaluations/validate — tender: {title}",
        title=payload.requirements.get("titre_marche", "unknown"),
    )

    try:
        result = await validate_and_refine(
            requirements=payload.requirements,
            dossier=payload.dossier,
        )
        logger.info(
            "Validation complete — score={score} verdict={verdict} refined={r}",
            score=result.score,
            verdict=result.verdict,
            r=result.refined,
        )
        return result

    except ValueError as exc:
        # LLM returned malformed JSON — surface as 502 (bad gateway / upstream failure)
        logger.error("Validation pipeline ValueError: {err}", err=str(exc))
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=f"LLM response parsing failed: {exc}",
        )
    except Exception as exc:
        logger.error("Validation pipeline unexpected error: {err}", err=str(exc), exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Internal server error during validation.",
        )


